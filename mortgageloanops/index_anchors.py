def index_at(reg, y, m):
    a = ANCH[reg]; t = (y - 2016) * 12 + m
    for (y0, m0, v0), (y1, m1, v1) in zip(a, a[1:]):
        i0, i1 = (y0 - 2016) * 12 + m0, (y1 - 2016) * 12 + m1
        if i0 <= t <= i1:
            s = (1 - math.cos(math.pi * (t - i0) / (i1 - i0))) / 2
            return v0 + (v1 - v0) * s
    return a[-1][2]


