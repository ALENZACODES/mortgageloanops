    if f == "P": return "NON"
    if f == "T": return "CGY" if fsa[:2] in ("T2", "T3", "T1") and fsa[:3] not in ("T1A","T1B","T1C","T1H","T1J","T1K","T1R","T1P","T1V") else ("EDM" if fsa[:2] in ("T5", "T6", "T8") else "ABO")
    if f == "V": return "VAN" if fsa[:2] in ("V5", "V6", "V7", "V3") else "BCO"
    if f == "H": return "MTL"
    if f in "GJ": return "QCO"
    if f in "RS": return "PRA"
    if f in "ABCE": return "ATL"
    return "TER"
